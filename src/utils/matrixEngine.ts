export const font5x8_yo_upper = [0x7F, 0x4B, 0x4A, 0x43, 0x62];
export const font5x8_yo_lower = [0x38, 0x55, 0x54, 0x55, 0x18];
const blank_glyph = [0, 0, 0, 0, 0];

export function getGlyph(code: number): number[] {
  if (code >= 32 && code <= 126) return font5x8_ascii[code - 32] || blank_glyph;
  if (code >= 0x0410 && code <= 0x042F) return font5x8_ru_upper[code - 0x0410] || blank_glyph;
  if (code >= 0x0430 && code <= 0x044F) return font5x8_ru_lower[code - 0x0430] || blank_glyph;
  if (code === 0x0401) return font5x8_yo_upper;
  if (code === 0x0451) return font5x8_yo_lower;
  if (code === 0x00B0) return font5x8_ascii['o'.charCodeAt(0) - 32] || blank_glyph;
  return blank_glyph;
}

export function measureStringWidth(text: string): number {
  return Array.from(text).length * 6;
}

/**
 * Serpentine / Zigzag matrix mapping from user's code:
 * inline int XY(int x, int y) {
 *   if (x < 0 || x >= WIDTH || y < 0 || y >= HEIGHT) return -1;
 *   return (x & 1) == 0 ? x * HEIGHT + y : x * HEIGHT + (HEIGHT - 1 - y);
 * }
 */
export function XY(x: number, y: number): number {
  if (x < 0 || x >= WIDTH || y < 0 || y >= HEIGHT) return -1;
  return (x & 1) === 0 ? x * HEIGHT + y : x * HEIGHT + (HEIGHT - 1 - y);
}

export type RGB = { r: number; g: number; b: number };

export const COLOR_PALETTE: Record<string, RGB> = {
  Green: { r: 0, g: 255, b: 0 },
  Cyan: { r: 0, g: 255, b: 255 },
  Yellow: { r: 255, g: 230, b: 0 },
  Red: { r: 255, g: 0, b: 0 },
  Blue: { r: 30, g: 120, b: 255 },
  Purple: { r: 180, g: 50, b: 255 },
  White: { r: 255, g: 255, b: 255 },
  Orange: { r: 255, g: 140, b: 0 },
  Pink: { r: 255, g: 20, b: 147 },
};

export type WeatherType = 'Clear' | 'Clouds' | 'Rain' | 'Snow' | 'Thunder' | 'Fog' | 'Unknown';

export interface FrameState {
  displayTime: string;
  weatherTemp: string;
  weather: WeatherType;
  scrollText: string;
  scrollX: number;
  isMusicMode: boolean;
  colorClock: string;
  colorText: string;
  colorWeather: string;
  isWifiConnected: boolean;
  isMqttConnected: boolean;
  brightness: number; // 10..255
  timeMs: number;
  isOtaMode?: boolean;
  otaProgress?: number; // 0..100
  otaStatus?: 'downloading' | 'writing' | 'success' | 'error';
}

export function renderMatrixFrame(state: FrameState): RGB[] {
  const buffer: RGB[] = Array.from({ length: NUM_LEDS }, () => ({ r: 0, g: 0, b: 0 }));

  const setPixel = (x: number, y: number, color: RGB) => {
    if (x < 0 || x >= WIDTH || y < 0 || y >= HEIGHT) return;
    const idx = XY(x, y);
    if (idx >= 0 && idx < NUM_LEDS) {
      buffer[idx] = color;
    }
  };

  const drawStringAt = (str: string, startX: number, startY: number, color: RGB) => {
    let cx = startX;
    for (const char of Array.from(str)) {
      const code = char.charCodeAt(0);
      const glyph = getGlyph(code);
      for (let col = 0; col < 5; col++) {
        const colByte = glyph[col] || 0;
        for (let row = 0; row < 8; row++) {
          if (colByte & (1 << row)) {
            setPixel(cx + col, startY + row, color);
          }
        }
      }
      cx += 6;
    }
  };

  const colClock = COLOR_PALETTE[state.colorClock] || COLOR_PALETTE.Green;
  const colText = COLOR_PALETTE[state.colorText] || COLOR_PALETTE.Cyan;
  const colWeather = COLOR_PALETTE[state.colorWeather] || COLOR_PALETTE.Yellow;
  const m = state.timeMs;

  // Check if special OTA simulation screen is requested
  if (state.isOtaMode) {
    const otaCol: RGB = { r: 50, g: 180, b: 255 };
    drawStringAt("OTA", 2, 0, otaCol);
    const pctStr = `${Math.min(100, Math.max(0, state.otaProgress || 0))}%`;
    const pctW = measureStringWidth(pctStr);
    drawStringAt(pctStr, WIDTH - pctW, 0, { r: 255, g: 255, b: 255 });

    // Progress bar across row 11 to 14
    const barWidth = Math.round((WIDTH - 4) * ((state.otaProgress || 0) / 100));
    for (let x = 2; x < WIDTH - 2; x++) {
      const isFilled = x - 2 < barWidth;
      const c = isFilled ? (state.otaStatus === 'error' ? { r: 255, g: 30, b: 30 } : { r: 0, g: 255, b: 120 }) : { r: 30, g: 40, b: 50 };
      setPixel(x, 10, c);
      setPixel(x, 11, c);
    }

    if (state.otaStatus === 'success') {
      drawStringAt("OK REBOOT", 0, 8, { r: 0, g: 255, b: 100 });
    } else if (state.otaStatus === 'error') {
      drawStringAt("ERR FAIL", 0, 8, { r: 255, g: 50, b: 50 });
    }

    // Apply brightness scaling
    const scale = state.brightness / 255;
    return buffer.map(c => ({
      r: Math.round(c.r * scale),
      g: Math.round(c.g * scale),
      b: Math.round(c.b * scale),
    }));
  }

  // Row 0..7: Clock Time centered
  const timeW = measureStringWidth(state.displayTime);
  const timeX = Math.floor((WIDTH - timeW) / 2);
  drawStringAt(state.displayTime, timeX, 0, colClock);

  // Row 8..15: Weather or Running Text
  if (state.isMusicMode) {
    drawStringAt(state.scrollText, state.scrollX, 8, colText);
  } else {
    const tempW = measureStringWidth(state.weatherTemp);
    const totalW = tempW + 3 + 8;
    const groupStartX = Math.floor((WIDTH - totalW) / 2);
    drawStringAt(state.weatherTemp, groupStartX, 8, colWeather);

    // Weather Icon at groupStartX + tempW + 3
    const iconX = groupStartX + tempW + 3;
    const iconY = 8;

    const drawCloudBase = (x: number, y: number, darkBase: boolean) => {
      const white: RGB = { r: 200, g: 200, b: 200 };
      const grayLight: RGB = { r: 140, g: 140, b: 155 };
      const grayDark: RGB = darkBase ? { r: 70, g: 70, b: 90 } : { r: 110, g: 110, b: 125 };
      setPixel(x + 2, y + 1, white);
      setPixel(x + 3, y + 1, white);
      setPixel(x + 5, y + 1, white);
      setPixel(x + 6, y + 1, white);
      for (let i = 1; i <= 7; i++) setPixel(x + i, y + 2, grayLight);
      for (let i = 0; i <= 8; i++) setPixel(x + i, y + 3, grayDark);
    };

    if (state.weather === 'Clear') {
      // Pulsing and spinning rays
      const phase = Math.sin((m / 400) * Math.PI) * 50 + 205;
      const coreColor: RGB = { r: phase, g: Math.max(0, phase - 40), b: 0 };
      setPixel(iconX + 2, iconY + 2, coreColor);
      setPixel(iconX + 3, iconY + 2, coreColor);
      setPixel(iconX + 1, iconY + 3, coreColor);
      setPixel(iconX + 4, iconY + 3, coreColor);
      setPixel(iconX + 1, iconY + 4, coreColor);
      setPixel(iconX + 4, iconY + 4, coreColor);
      setPixel(iconX + 2, iconY + 5, coreColor);
      setPixel(iconX + 3, iconY + 5, coreColor);

      if (Math.floor(m / 250) % 2 === 0) {
        setPixel(iconX + 2, iconY, colWeather);
        setPixel(iconX + 3, iconY, colWeather);
        setPixel(iconX + 2, iconY + 7, colWeather);
        setPixel(iconX + 3, iconY + 7, colWeather);
        setPixel(iconX, iconY + 3, colWeather);
        setPixel(iconX, iconY + 4, colWeather);
        setPixel(iconX + 6, iconY + 3, colWeather);
        setPixel(iconX + 6, iconY + 4, colWeather);
      } else {
        setPixel(iconX, iconY + 1, colWeather);
        setPixel(iconX + 5, iconY + 1, colWeather);
        setPixel(iconX, iconY + 6, colWeather);
        setPixel(iconX + 5, iconY + 6, colWeather);
      }
    } else if (state.weather === 'Clouds') {
      drawCloudBase(iconX + (Math.floor(m / 900) % 2), iconY + 1, false);
    } else if (state.weather === 'Rain') {
      drawCloudBase(iconX, iconY, true);
      const blue: RGB = { r: 30, g: 120, b: 255 };
      setPixel(iconX + 2, iconY + (Math.floor(m / 130) % 5) + 4, blue);
      setPixel(iconX + 4, iconY + (Math.floor(m / 160) % 5) + 4, blue);
      setPixel(iconX + 6, iconY + (Math.floor(m / 110) % 5) + 4, blue);
    } else if (state.weather === 'Snow') {
      drawCloudBase(iconX, iconY, false);
      const white: RGB = { r: 255, g: 255, b: 255 };
      setPixel(iconX + 2 + (Math.floor(m / 600) % 2), iconY + (Math.floor(m / 300) % 5) + 4, white);
      setPixel(iconX + 5 + (Math.floor((m + 300) / 600) % 2), iconY + (Math.floor(m / 350) % 5) + 4, white);
    } else if (state.weather === 'Thunder') {
      drawCloudBase(iconX, iconY, true);
      const bolt: RGB = (Math.floor(m / 180) % 4 === 0) ? { r: 255, g: 255, b: 255 } : { r: 255, g: 220, b: 0 };
      setPixel(iconX + 4, iconY + 4, bolt);
      setPixel(iconX + 3, iconY + 5, bolt);
      setPixel(iconX + 4, iconY + 5, bolt);
      setPixel(iconX + 3, iconY + 6, bolt);
      setPixel(iconX + 2, iconY + 7, bolt);
    } else if (state.weather === 'Fog') {
      const shift = Math.floor(m / 450) % 3;
      for (let i = 0; i < 8; i += 2) {
        setPixel(iconX + i, iconY + 2 + shift, { r: 120, g: 140, b: 145 });
        setPixel(iconX + i + 1, iconY + 5 - shift, { r: 90, g: 110, b: 120 });
      }
    } else {
      drawStringAt("?", iconX + 1, iconY, colWeather);
    }
  }

  // Draw WiFi Alert glyph if disconnected (top-left)
  if (!state.isWifiConnected) {
    const isBlink = Math.floor(m / 350) % 2 === 1;
    const c: RGB = isBlink ? { r: 255, g: 0, b: 0 } : { r: 80, g: 0, b: 0 };
    setPixel(0, 1, c);
    setPixel(1, 0, c);
    setPixel(1, 2, c);
    setPixel(2, 1, c);
    setPixel(0, 5, c);
    setPixel(1, 4, c);
    setPixel(2, 3, c);
    setPixel(3, 2, c);
  } else if (!state.isMqttConnected) {
    // Draw MQTT Alert glyph if disconnected (top-right)
    const isBlink = Math.floor(m / 450) % 2 === 1;
    const c: RGB = isBlink ? { r: 255, g: 140, b: 0 } : { r: 90, g: 40, b: 0 };
    const x = WIDTH - 4;
    setPixel(x, 0, c);
    setPixel(x + 1, 0, c);
    setPixel(x + 2, 0, c);
    setPixel(x + 3, 0, c);
    setPixel(x, 3, c);
    setPixel(x + 1, 4, c);
    setPixel(x + 2, 5, c);
    setPixel(x + 3, 6, c);
  }

  // Apply brightness scaling (FastLED setBrightness equivalent)
  const scale = state.brightness / 255;
  return buffer.map(c => ({
    r: Math.round(c.r * scale),
    g: Math.round(c.g * scale),
    b: Math.round(c.b * scale),
  }));
}
